package com.sawan4art.noor.data.update

/**
 * قنوات الإصدار الثلاث — بلاغ المالك v1.71: «في زر التحديثات عايز اضيف
 * كذا اصدار قابلين للتحميل من قبل المستخدم النسخه المستقره و البيتا و
 * الاصدار التجريبي و في كل مره يتم تعديل او ضافه تحديثات في المستقبل
 * منا نحن يجب التنويه بان الاصدار مستقر ام بيتا ام اصدار تجريبي و يمكن
 * للمستخدم تفعيل اشعارات النسخ المستقره فقط او اي نسخ اخرى».
 *
 * فالقناة تُقرأ من **الوسم نفسه**: النسخة بلا مرحلةٍ («v1.71») مستقرة،
 * وبمرحلة beta («v1.71-beta1») بيتا، وبمرحلة alpha («v1.71-alpha2»)
 * تجريبية — وبهذا التنويهُ الآلي يأتي مع كل إصدارٍ قادمٍ من فريقنا
 * بلا تدخل يدوي، والقنوات الثلاث تُعرض في قسم «التحديثات» كلٌّ بأحدث
 * نسخةٍ له ويمكن تنزيل أيٍّ منها من داخل التطبيق.
 */
enum class UpdateChannel(
    val title: String,
    val subtitle: String,
) {
    /** المستقرة — بلا مرحلةٍ في الوسم: «v1.71» */
    STABLE("المستقرة", "النسخة الرسمية المضمونة — مناسبة للجميع"),

    /** البيتا — مرحلة beta في الوسم: «v1.71-beta1» */
    BETA("البيتا", "مميزات جديدة شبه مكتملة — قد يفلت منها خطأ"),

    /** التجريبية — مرحلة alpha في الوسم: «v1.71-alpha1» */
    ALPHA("التجريبية", "أحدث الميزات أولًا وقبل نضجها — لأصحاب التجربة"),

    ;

    companion object {

        /**
         * قناة الوسم من مراحل [NoorVersion]: alpha → تجريبية، beta → بيتا،
         * وrc وما بعده والبلا مرحلةٍ → مستقرة، والوسم غير المفهوم → مستقرة
         * بأمانٍ (الإصدارات القديمة كلها مستقرة).
         */
        fun ofTag(tag: String?): UpdateChannel {
            val version = NoorVersion.parse(tag) ?: return STABLE
            return when (version.stageRank) {
                NoorVersion.STAGE_ALPHA -> ALPHA
                NoorVersion.STAGE_BETA -> BETA
                else -> STABLE
            }
        }

        /** قناة من قيمة الإعداد المخزّنة — «stable» أو «all» والغريب يعود للمستقرة */
        fun fromNotifyPref(value: String?): Boolean =
            value == NOTIFY_PREF_ALL

        /** قيمة الإعداد: إشعارات المستقرة فقط */
        const val NOTIFY_PREF_STABLE = "stable"

        /** قيمة الإعداد: إشعارات كل النسخ (مستقرة وبيتا وتجريبية) */
        const val NOTIFY_PREF_ALL = "all"
    }
}
