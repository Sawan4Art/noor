package com.sawan4art.noor.data.update

/**
 * سياسة إشعار النسخ الجديدة — قرار نقّي قابل للاختبار بلا سياق ولا شبكة.
 *
 * alpha37 بلاغ المالك: «الاشعار بتاع التحديث وصل مره واحده — انا عايز
 * الاشعار ده يوصل لو كتير لو المستخدم محدثش التطبيق».
 *
 * القاعدة القديمة كانت «إشعار واحد لكل نسخة» — تُخزَّن النسخة بعد النشر
 * ولا يعاد الإشعار بها أبداً حتى لو لم يحدّث المستخدم طوال حياته.
 * القاعدة الجديدة: **الإشعار يتكرر ما دام التحديث لم يُثبَّت**:
 * - نسخة لم تُشعَر عنها من قبل → أَشعِر فوراً.
 * - النسخة نفسها والفترة منذ آخر إشعار بلغت فترة التذكير → أَشعِر من جديد
 *   (تذكير دوري، والفحص عند كل فتح + الدوري كل ١٢ ساعة يضمنان ألا يمضي
 *   يوم كامل دون تذكير).
 * - النسخة نفسها داخل فترة التذكير → لا إشعار (لا ازدحام داخل الجلسة).
 * - المرشح أقدم من آخر نسخة أُشعر عنها → لا إشعار أبداً (رجوع لنسخة قديمة
 *   لا يستحق تنبيهاً).
 *
 * التثبيت يُنهي الدورة طبيعياً: بعد التحديث لا يوجد مرشح أحدث فلا فحص
 * يمرر تحديثاً أصلاً.
 */
object UpdateNotifyPolicy {

    /** فترة تذكير النسخة نفسها — كل ١٢ ساعة يتذكّر المستخدم بالتحديث المعلّق */
    const val REPEAT_INTERVAL_MS = 12L * 60 * 60 * 1000

    fun shouldNotify(
        notifiedVersion: String?,
        lastNotifiedAt: Long,
        candidateTag: String,
        now: Long,
    ): Boolean = when {
        notifiedVersion == null -> true
        NoorVersion.isNewer(candidateTag, notifiedVersion) -> true
        candidateTag == notifiedVersion -> now - lastNotifiedAt >= REPEAT_INTERVAL_MS
        else -> false
    }
}
