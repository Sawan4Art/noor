package com.sawan4art.noor.ui.theme

import kotlin.math.hypot
import kotlin.math.sqrt

/**
 * رياضيات «مزلاج الشمس والقمر» — كوتلن خالص بلا أي اعتمادات Compose كي تُختبر وحدةً.
 *
 * قواعد المالك (2026-10-31) وتعديلاته (2026-10-31 عصراً):
 * 1) السحب لليمين = فاتح، وليسار = مظلم، والأيقونة تمشي مع اليد حرفياً
 *    (ما لم تُرفع اليد تبقى ممسوكة حيث هي — حتى في منتصف المسار).
 * 2) أثناء السحب تنقسم الشاشة نفسها: **النصف الفاتح يسار الحدّ والمظلم يمينه
 *    دائماً**، وقصّ المعاينة **صلب** (clipRect) بلا أي قناع DstIn ولا طبقة
 *    Offscreen — الآلية القديمة كانت تفشل بصمت على أجهزة معينة (بلاغ المالك:
 *    الشاشة بفتحها ظلت مظلمة والانقسام لم يظهر قط) والقص الصلب مستحيل الفشل.
 * 3) الفصل **حاد وصريح** (توجيه المالك alpha15، 2026-10-31 مساءً — كلمة أخيرة
 *    تلغي الحزام العريض 0.22 الذي حاكى موك-أب alpha14): النصف الفاتح كامل
 *    بوضوح والنصف المظلم كامل بوضوح، والفاصل بينهما **خط ضوء رفيع** لا غير —
 *    والتوهج مركّز حصرياً على حافة خط الحركة (لا حزام في الجهة المسيطرة ولا
 *    بؤرة إهليلجية).
 * 4) عند الرفع: الضفة التي عبرها الإصبع من المنتصف تحسم الوضع،
 *    وإلا رجعت الأيقونة إلى مرساها بالسائل نفسه.
 * 5) النقرة (بلا سحب) = تبديل فوري برحلة الشمس من مرساها — نفس حيوية الشريط السفلي.
 * 6) تغيير المظهر لا يعمل إلا من خلال الأيقونة نفسها — لا الإمساك بالمسار ولا الفراغ.
 * 7) **توهج الضوء المنبعث من النهار نفسه** — بلا أي خط (توجيه المالك alpha17
 *    بعد alpha16: «كبر عرض الخط شويه وشيل الخط وخلّي التوهج فقط»): حقل
 *    توهج واحد ناعم أعرض من قبل (30dp) لا حافة له ولا خيط، **متدرّج بألوان
 *    كثيرة** (طيف نهاري دافئ بطول الشاشة)، وشدة إضاءته **ديناميكية مع
 *    السحب**: تبدأ ضعيفة وتزداد تدريجياً حتى تبلغ شدة إضاءة الوضع النهاري
 *    نفسها لحظة غمر الشاشة بالفاتح، **والعكس صحيح** نحو المظلم: تبدأ عالية
 *    وتنحدر تدريجياً حتى الانطفاء — النهار هو مصدر الضوء الوحيد (beamIntensity).
 *
 * الاتجاه ثابت فيزيائياً (يسار الشاشة = فاتح) مهما كان اتجاه التخطيط RTL.
 */
object ThemeDialMath {

    /** أقصى مسافة حركة تُعدّ نقرة لا سحباً */
    const val TAP_SLOP_PX = 14f

    /** تقدّم المزلاج: 0 = مظلم (مرسى اليسار)، 1 = فاتح (مرسى اليمين) */
    fun progress(iconX: Float, anchorLeft: Float, anchorRight: Float): Float {
        val span = anchorRight - anchorLeft
        if (span <= 0f) return 0f
        return ((iconX - anchorLeft) / span).coerceIn(0f, 1f)
    }

    /** حصر موضع الأيقونة داخل المسار بين المرسيين */
    fun clampX(x: Float, anchorLeft: Float, anchorRight: Float): Float =
        x.coerceIn(anchorLeft, anchorRight)

    /** هل إيماءة الرفع نقرة (تبديل) أم سحب؟ */
    fun isTap(totalDx: Float, totalDy: Float, slopPx: Float = TAP_SLOP_PX): Boolean =
        hypot(totalDx, totalDy) <= slopPx

    /**
     * قرار التثبيت عند رفع اليد من السحب: الضفة التي يقف عليها الإصبع من منتصف
     * المسار تحسم الوضع (فاتح يمين المنتصف، مظلم يساره) — وإلا فالرجوع لمرسى البداية.
     */
    fun commitLight(releaseX: Float, anchorLeft: Float, anchorRight: Float): Boolean =
        releaseX >= (anchorLeft + anchorRight) / 2f

    /**
     * شفافيتا الشمس والقمر — الظهور التدريجي محصور في نطاق النصفة:
     * القمر ثابت كامل حتى 0.35 ثم يذوب لصالح الشمس حتى 0.65 (مجموعهما 1 دائماً).
     */
    fun sunAlpha(p: Float): Float = ((p - 0.35f) / 0.3f).coerceIn(0f, 1f)

    fun moonAlpha(p: Float): Float = sunAlpha(1f - p)

    /**
     * شدة التوهج المنبعث من الوضع النهاري عند حدّ الانقسام — **نسبة النهار على
     * الشاشة** (روح توجيه alpha16، وalpha17 أزال الخيط وأبقى التوهج فقط):
     *
     * «عايز خط الضوء الرفيع ده شدة إضاءته تزداد مع السحب وتبدأ بإضاءة ضعيفة...
     * عند التبديل إلى الوضع النهاري تبدأ شدة سطوع الضوء ضعيفة ثم تزداد تدريجياً
     * حتى تصل إلى نفس شدة إضاءة الوضع النهاري في نهاية المطاف، والعكس صحيح عند
     * التبديل إلى الوضع الليلي تبدأ الإضاءة بشدة عالية ثم تنحدر تدريجياً إلى
     * النهاية».
     *
     * النهار هو مصدر الضوء الوحيد: شدة التوهج = مقدار ما احتله النهار من الشاشة
     * (maskX/screenW) — معادلة واحدة متناسقة تلبي الاتجاهين تلقائياً («والعكس
     * صحيح» بلا تفرّع): السحب نحو الفاتح يبدأ خافتاً عند مرسى المظلم ويزداد مع
     * كل بكسل حتى يبلغ الإضاءة الكاملة لحظة غمر الشاشة بالنهار، والسحب نحو
     * المظلم يبدأ ساطعاً وينحدر حتى ينطفئ تماماً. الجذر التربيعي يرفع بداية
     * الرحلة كي يُرى التوهج خافتاً لا معدوماً من أول سحبة (الخطّي يبدأ شبه
     * مخفي) — والحدّان مضبوطان حرفياً: 0 عند مظلم كامل و1 عند فاتح كامل.
     *
     * maskX موضع حدّ الانقسام بالبكسل (يساره فاتح دائماً)، screenW عرض الشاشة.
     */
    fun beamIntensity(maskX: Float, screenW: Float): Float {
        if (screenW <= 0f) return 0f
        val dayFraction = (maskX / screenW).coerceIn(0f, 1f)
        return sqrt(dayFraction)
    }

    /**
     * هدف امتداد الحدّ عند التثبيت: يُساق خارج الشاشة حتى يخرج **التوهج بكامل
     * امتداده** كي تغطي الطبقة الهدف الشاشة كلها بلا حافة ولا بقايا توهج لحظة
     * قلب الثيم (التثبيت الفاتح يخرج يميناً، والمظلم يساراً — الامتداد متناسب
     * الاتجاهين). الامتداد المعطى = **الامتداد الكلي** لحقل التوهج بالبكسل
     * (ريشة + انتشار + هامش ميت) — أوسع ما يُرسم حول الحدّ.
     */
    fun sweepTargetX(commitLight: Boolean, screenW: Float, edgeExtentPx: Float): Float =
        if (commitLight) screenW + edgeExtentPx.coerceAtLeast(1f) else -edgeExtentPx.coerceAtLeast(1f)

    // ===== هندسة التوهج وحزام البلور (alpha19) — دوال نقية تُختبر وحدةً =====

    /** أجزاء حقل التوهج حول الحدّ — مصدر واحد للرسم والمرآة والاختبارات */
    object GlowGeometry {
        /** ريشة البلور على جانبي الحدّ (نصف حزام المزج) */
        const val FEATHER_DP = 12f
        /** امتداد الانحدار المرئي يمين الحدّ (الجهة المظلمة) */
        const val SPREAD_DP = 44f
        /** هامش ميت يمين الانحدار — يبلغ القناع صفراً فيه قبل طرف الطبقة */
        const val DEAD_DP = 14f

        /** الامتداد الكلي الذي يُساق به الحدّ خارج الشاشة */
        val TOTAL_DP: Float = FEATHER_DP + SPREAD_DP + DEAD_DP
    }

    /**
     * وقفات قناع التوهج الأفقي (موضع نسبي 0..1 على حقل التوهج ← شفافية نسبية
     * إلى الطاقة) — صعود ناعم عبر حزام البلور، ذروة بعد الحدّ، انحدار رتيب،
     * وصفر حقيقي من 0.955 حتى الطرف (موثّ الخط الأحمر على حرف الطبقة).
     * الحدّ نفسه يقع عند t = FEATHER/TOTAL ≈ 0.171.
     */
    fun glowMaskStops(power: Float): List<Pair<Float, Float>> = listOf(
        0.000f to 0f,
        0.080f to 0.14f * power,
        0.171f to 0.46f * power,
        0.243f to 0.72f * power,
        0.420f to 0.36f * power,
        0.600f to 0.14f * power,
        0.780f to 0.045f * power,
        0.900f to 0.008f * power,
        0.955f to 0f,
        1.000f to 0f,
    )

    /**
     * وقفات قناع حزام البلور حول حدّ الانقسام (شفافية الطبقة الهدف عبر الحزام)
     * — كامل عند جهة الطبقة الصلبة ← صفر عند جهة الأساس، ومزج 50/50 عند الحدّ
     * نفسه — هذا هو «البلور» الذي يسيح الحدّ مع اللون.
     */
    fun splitFeatherStops(lightOverlay: Boolean): List<Pair<Float, Float>> =
        if (lightOverlay) {
            listOf(
                0.00f to 1f,
                0.28f to 0.78f,
                0.50f to 0.5f,
                0.72f to 0.22f,
                1.00f to 0f,
            )
        } else {
            listOf(
                0.00f to 0f,
                0.28f to 0.22f,
                0.50f to 0.5f,
                0.72f to 0.78f,
                1.00f to 1f,
            )
        }
}
