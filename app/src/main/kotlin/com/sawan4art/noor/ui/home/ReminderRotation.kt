 *   alpha11 محفوظة: بداية عشوائية مع كل فتحٍ للتطبيق).
 */
object ReminderRotation {

    /**
     * المؤشّر التالي بعد قلبٍ للثيم — يتقدّم دائماً ويلتفّ حول القائمة.
     * قائمة بعنصر واحد (أو أقل) تعيد الصفر عاجزةً عن الدوران.
     */
    fun nextIndex(current: Int, size: Int): Int {
        if (size <= 1) return 0
        val cur = current.coerceIn(0, size - 1)
        return (cur + 1) % size
    }
}

