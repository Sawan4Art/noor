 * جمل التذكير الدوّارة (توجيه المالك alpha24):
 * «عايز مع كل تغيير لمظهر الوضع الليلي او النهاري تتغير جمله التذكير
 * و زود عددهم اكثر» — السطر السفلي (الصدقة الجارية) وشريط التذكير فوق
