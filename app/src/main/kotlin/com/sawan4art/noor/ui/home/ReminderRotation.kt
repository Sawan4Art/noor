 * (ملتفّاً حول القائمة) — فتظهر جملة **مختلفة حتماً** مع كل قلب،
 * ولا يُترك للتوزيع العشوائي أن يُعيد الجملة نفسها مرتين متتاليتين.
 * (شريط التذكير يحتفظ بعادة alpha11: اختيار بداية عشوائي مع كل فتح
 * للتطبيق — ثم يدور حتمياً مع الأقلبات بعدها).
 */
object ReminderRotation {

    /**
     * المؤشّر التالي بعد قلبٍ للثيم — يتقدّم دائماً ويلتفّ حول القائمة.
     * قائمة بعنصر واحد (أو أقل) تعيد الصفر عاجزةً عن الدوران.
     */
    fun nextIndex(current: Int, size: Int): Int {
        if (size <= 1) return 0
        val cur = current.coerceIn(0, size - 1)
        return (cur + 1) % size
    }
}

