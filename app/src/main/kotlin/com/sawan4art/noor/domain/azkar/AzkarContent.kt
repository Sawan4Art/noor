/**
 * الأذكار — قسم الأذكار المكتمل (alpha27، توجيه المالك السابق:
 * «الصلاه على النبي ده ذكر لوحده .. في المسبحه هنحط المهم فقط اما في
 * قسم الاذكار مستقبلا هنحط اذكار كتير») — هذا القسم هو المكان الموعود:
 *
 * ١. **الصلاة على النبي ﷺ** ذكرٌ مستقل بعدّاد حرّ — لا تدخل تسبيح
 *    ما بعد الصلاة إطلاقاً (عقد MisbahaDhikrList قائم).
 * ٢. أذكار الصباح والمساء والنوم — مختارات مسندة بنصوصها المشكولة
 *    ومصادرها، كل ذكرٍ بعدده المسنون.
 *
 * النصوص مكتوبة بالتشكيل كما في كتب الأذكار المعتمدة (حصن المسنون
 * وأمثاله)، والفواصل بين الآيات في السور «،» لسلاسة القراءة في سطر
 * واحد. المصادر مقتضبة صريحة: «متفق عليه» = البخاري ومسلم، و«صححه
 * الألباني» لمن صحّحه في السلسلة الصحيحة.
 */
