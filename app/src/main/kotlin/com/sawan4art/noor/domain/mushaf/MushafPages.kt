package com.sawan4art.noor.domain.mushaf

/**
 * صفحات المصحف — رواية حفص مجوّد بالتشكيل الملون للتجويد.
 *
 * توجيه المالك (٢٠٢٦-١١-٠٥): «غير المصحف تماما انا عايز راويه حفص مجود
 * زي الصوره كده و يكون عرض صفحات المصحف بكامل الشاشه» — المصحف الجديد
 * كلُّه صور صفحات المصحف الملون بالتجويد نفسه بترقيم المدنة القياسي
 * (٦٠٤ صفحة، الصفحة ٥٠ مطلع آل عمران مثلاً)، فلا يُرسم نصٌّ داخل
 * التطبيق بل تُعرض صفحة المصحف المطبوع عينها.
 *
 * **توجيه المالك ٢٠٢٦-١١-٠٦ بعد alpha52: «صفحات المصحف تظهر علامه تحميل
 * انا مش عايز كده انا عايز التفاسير و المصحف يكونوا داخل التطبيق بشكل
 * دائم مش يتم تحميلهم كل مره يعني كل الصفحات والتفاسير تكون داخل الكود
 * علشان ميظهرش ابدا ان الصفحه بتحمل»** — الصفحات الستُّمِئة وأربع كلُّها
 * مرفق داخل التطبيق (assets/mushaf_pages) بصيغة WebP المصغَّرة الحجم
 * بنفس الدقة، فتُقرأ من ذاكرة الجهاز نفسها في لمح البصر بلا شبكة وبلا
 * أي ظهور لتحميل أبداً، والتفسير المرفق بقاعدة المصحف كذلك من alpha52.
 *
 * المصدر الأصلي للصور — مستودع عام مفتوح لصور «مصحف التجويد الملون»:
 * github.com/murtraja/quran-android-images-helper (المجلد images_1053).
 */
object MushafPages {

    /** عدد صفحات المصحف المدني القياسي — المصحف كله */
    const val PAGE_COUNT = 604

    /**
     * مسار الصفحة داخل مرفقات التطبيق — رقم الصفحة ١..٦٠٤ كما في
     * المصحف المطبوع وأسماء الملفات 1.webp حتى 604.webp.
     */
    fun assetPath(page: Int): String = "mushaf_pages/${clampPage(page)}.webp"

    /**
     * تقييد رقم الصفحة داخل ١..٦٠٤ — يُستخدم عند القراءة والكتابة معاً
     * فلا يعود قيمة مخزنة من نسخة قديمة أو إدخال خاطئ خارج النطاق.
     */
    fun clampPage(page: Int): Int = page.coerceIn(1, PAGE_COUNT)
}
