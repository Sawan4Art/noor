package com.sawan4art.noor.domain.mushaf

/**
 * أجزاء القرآن الثلاثون — توجيه المالك ٢٠٢٦-١١-٠٦: «بخصوص قائمه اختيار
 * السوره قبل الدخول على صفحات المصحف عايزها تكون فيها اختيار عرض اجزاء
 * القران».
 *
 * هذه أرقام الصفحات التي يبدأ عندها كل جزء في طبعة المدينة المدنية
 * المعتمدة (٦٠٤ صفحة) — ترقيم المصحف نفسه: الجزء الأول فاتحة الكتاب
 * (صفحة ١) والثاني مطلع البقرة «سيدَعلك» (صفحة ٢٢) … والثلاثون «عمَّ
 * يتحاءل» (صفحة ٥٨٢). أما اسم أول سورة في الجزء فيُقرأ من قاعدة
 * المصحف وقت العرض فلا تكرار لمصدرين.
 */
object MushafJuz {

    /** صفحة بداية كل جزء — المؤشر ٠ هو الجزء ١ حتى المؤشر ٢٩ للجزء ٣٠ */
    val START_PAGES = intArrayOf(
        1, 22, 42, 62, 82, 102, 121, 142, 162, 182,
        201, 222, 242, 262, 282, 302, 322, 342, 362, 382,
        402, 422, 442, 462, 482, 502, 522, 542, 562, 582,
    )

    /** عدد الأجزاء الثابت — القرآن كله */
    const val COUNT = 30

    /** صفحة بداية جزء ما (١..٣٠) — خارج النطاق يُقيَّد لأول أو آخر الأجزاء */
    fun startPage(juz: Int): Int {
        val index = (juz - 1).coerceIn(0, COUNT - 1)
        return START_PAGES[index].coerceIn(1, MushafPages.PAGE_COUNT)
    }
}
