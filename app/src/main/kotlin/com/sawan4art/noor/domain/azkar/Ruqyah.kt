package com.sawan4art.noor.domain.azkar

/**
 * الرقية الشرعية المعتمدة (alpha63) — بلاغ المالك: «عايز زر اضافي شبيه
 * بزري الصلاه على النبي و اسماء الله الحسنى تحت زر الصلاه علي النبي
 * يكون خاص بالرقيه الشرعيه المعتمده و الصحيحه».
 *
 * المحتوى هو الرقية الثابتة المسنونة كما جمعها أهل العلم:
 * - فواتح الرقية: الفاتحة (حديث أبي سعيد الخدري — متفق عليه) وآية
 *   الكرسي وآخر البقرة («من قرأ الآيتين من آخر البقرة في ليلة كفتاه»).
 * - آيات إبطال السحر: الأعراف ١١٧-١١٩ ويونس ٨١-٨٢ وطه ٦٩.
 * - المعوذات الثلاث ثلاثاً (حديث عائشة: كان ﷺ يعوذ نفسه حين يفترق
 *   من بيته بقراءة الإخلاص والمعوذتين ثم يمسح ناصيته ويده).
 * - الأدعية الثابتة بمصادرها: «أعوذ بكلمات الله التامات» (مسلم)،
 *   «بسم الله أرقيك» (رقية جبريل لعائشة — صحيح)، «اللهم رب الناس»
 *   (متفق عليه)، «أعوذ بعزة الله وقدرته» (مسلم).
 * - شروط الرقية الشرعية الثلاثة (ابن القيم في الطب النبوي).
 *
 * نصوص الآيات كلها تُقرأ من قاعدة المصحف نفسها [MushafDb.ayahText]
 * فلا نصٌّ مكتوبٌ يدوياً قد يخطئ — هنا فقط مواضعها وأسماؤها والأدعية
 * الثابتة بمصادرها. عقدٌ نقيٌّ بلا أندرويد يُختبر آلياً.
 */
object Ruqyah {

    /** موضع آيةٍ أو مُدى آياتٍ من المصحف */
    data class VerseRef(
        val sura: Int,
        /** أول آية */
        val from: Int,
        /** آخر آية — تساوي الأول في الآية الواحدة */
        val to: Int,
        /** عنوان الموضع كما يُعرض */
        val title: String,
    ) {
        val ayahs: IntRange get() = from..to
    }

    /** دعاء ثابت بنصه ومصدره */
    data class Dua(val text: String, val source: String)

    /** كتلة شاشة الرقية — عنوانٌ ووصفٌ ومحتوى آياتٍ أو أدعية */
    data class Block(
        val id: String,
        val title: String,
        val subtitle: String,
        val verses: List<VerseRef> = emptyList(),
        val duas: List<Dua> = emptyList(),
    )

    // ===== مواضع آيات الرقية في المصحف =====

    val FATIHAH = VerseRef(1, 1, 7, "سورة الفاتحة")
    val KURSI = VerseRef(2, 255, 255, "آية الكرسي — البقرة ٢٥٥")
    val BAKARAH_END = VerseRef(2, 285, 286, "آخر آيتين من سورة البقرة")
    val SIHR_AARAF = VerseRef(7, 117, 119, "من سورة الأعراف")
    val SIHR_YUNUS = VerseRef(10, 81, 82, "من سورة يونس")
    val SIHR_TAHA = VerseRef(20, 69, 69, "من سورة طه")
    val IKHLAS = VerseRef(112, 1, 4, "سورة الإخلاص")
    val FALAQ = VerseRef(113, 1, 5, "سورة الفلق")
    val NAS = VerseRef(114, 1, 6, "سورة الناس")

    /** مواضع الآيات بترتيب الرقية — «معتمدة وصحيحة» كما بلاغ المالك */
    val VERSES: List<VerseRef> = listOf(
        FATIHAH, KURSI, BAKARAH_END, SIHR_AARAF, SIHR_YUNUS, SIHR_TAHA,
        IKHLAS, FALAQ, NAS,
    )

    // ===== الأدعية الثابتة بمصادرها =====

    val DUAS: List<Dua> = listOf(
        Dua(
            "أَعُوذُ بِكَلِمَاتِ اللهِ التَّامَّاتِ مِنْ شَرِّ مَا خَلَقَ",
            "صحيح مسلم (٢١٠٨) — كان ﷺ يُعوذ بها الحسن والحسين",
        ),
        Dua(
            "بِسْمِ اللهِ أَرْقِيكَ، مِنْ كُلِّ شَيْءٍ يُؤْذِيكَ، مِنْ شَرِّ كُلِّ " +
                "نَفْسٍ أَوْ عَيْنِ حَاسِدٍ، اللهُ يَشْفِيكَ، بِسْمِ اللهِ أَرْقِيكَ",
            "رقية جبريل ﷺ للنبي ﷺ — صحيح (رواه مسلم عن عائشة)",
        ),
        Dua(
            "اللَّهُمَّ رَبَّ النَّاسِ، أَذْهِبِ الْبَاسَ، اشْفِ أَنْتَ الشَّافِي، " +
                "لَا شِفَاءَ إِلَّا شِفَاؤُكَ، شِفَاءً لَا يُغَادِرُ سَقَماً",
            "متفق عليه — كان ﷺ يعوذ بها ويمسح بمسحته موضع الألم",
        ),
        Dua(
            "بِسْمِ اللهِ (ثلاثاً) أَعُوذُ بِعِزَّةِ اللهِ وَقُدْرَتِهِ مِنْ " +
                "شَرِّ مَا أَجِدُ وَأُحَاذِرُ (سبعاً)",
            "صحيح مسلم (٢٢٠٢) — للوجع في الجسد، ويوضع يده على موضع الألم",
        ),
    )

    // ===== كتل الشاشة =====

    val BLOCKS: List<Block> = listOf(
        Block(
            id = "intro",
            title = "أولاً — أصل الرقية",
            subtitle = "ما رُوي عن النبي ﷺ في أصلها وشروطها",
            duas = listOf(
                Dua(
                    "الرقية الشرعية: أن يستشفى المسلم بكلام الله تعالى وأسمائه " +
                        "ووصفاته، وبالدعاء الثابت عن النبي ﷺ — وقد رُوي أن جبريل " +
                        "رقى النبي ﷺ بقوله: «بسم الله أرقيك».",
                    "من الطب النبوي لابن القيم",
                ),
                Dua(
                    "شروط الرقية الشرعية الثلاثة: أن تكون بكلام الله أو أسمائه " +
                        "وصفاته، وأن تكون باللسان العربي أو بما يُعرف معناه، وأن " +
                        "يُعتقد أن الرقية لا تؤثر بذاتها بل بقدر الله تعالى.",
                    "ابن القيم في الطب النبوي",
                ),
            ),
        ),
        Block(
            id = "fatiha",
            title = "فاتحة الكتاب",
            subtitle = "حديث أبي سعيد الخدري لما رقاها على سيد من بني عامر فقام " +
                "كأنما عُقد من عقال — «وما يدريك أنها رقية؟» — متفق عليه",
            verses = listOf(FATIHAH),
        ),
        Block(
            id = "kursi_end",
            title = "آية الكرسي وآخر البقرة",
            subtitle = "«من قرأ آية الكرسي حين يأخذ مضجعه لم يقربه شيطان حتى " +
                "يصبح» (البخاري) — و«من قرأ الآيتين من آخر البقرة في ليلة " +
                "كفتاه» (متفق عليه)",
            verses = listOf(KURSI, BAKARAH_END),
        ),
        Block(
            id = "sihr",
            title = "آيات إبطال السحر",
            subtitle = "كلام الله في حكمة عيسى وإبراهيم وموسى عليهما الصلاة " +
                "والسلام — «فوقع الساحرون ساجدين» و«أدرك باطلهم» و«فلم يزدوه " +
                "إلا سواداً» — وهي المواضع التي يوردها أهل العلم في الرقية",
            verses = listOf(SIHR_AARAF, SIHR_YUNUS, SIHR_TAHA),
        ),
        Block(
            id = "muawwizat",
            title = "المعوذات ثلاثاً",
            subtitle = "حديث عائشة: كان النبي ﷺ إذا أصابه شيء يقرأ المعوذات " +
                "وينفث في يديه ويمسح بهما — و«قل هو الله أحد» و«قل أعوذ برب " +
                "الفلق» و«قل أعوذ برب الناس» تكفيك من كل شيء",
            verses = listOf(IKHLAS, FALAQ, NAS),
        ),
        Block(
            id = "duas",
            title = "الأدعية الثابتة",
            subtitle = "أدعية مأثورة عن النبي ﷺ بمصادرها — تُقال بوضع اليد " +
                "على موضع الألم أو الوجع",
            duas = DUAS,
        ),
    )

    /** عدد آيات الرقية كلها — للاختبار والعرض */
    fun verseCount(): Int = VERSES.sumOf { it.ayahs.count() }

    /** هل الموضع سليم داخل المصحف؟ — عقدُ الاختبار */
    fun isValid(ref: VerseRef): Boolean =
        ref.sura in 1..114 && ref.from in 1..286 && ref.to >= ref.from && ref.to <= ref.from + 30
}
