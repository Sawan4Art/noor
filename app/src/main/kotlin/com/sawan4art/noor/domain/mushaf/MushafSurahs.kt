package com.sawan4art.noor.domain.mushaf

/**
 * أسماء السور ال١١٤ بالعربية المعتمدة وترقيمها المدني — للعناوين النصية
 * (علامة مرجعية، مشاركة، نسخ، تلاوة). أما عدّ آيات كل سورة فيُقرأ من
 * قاعدة المصحف نفسها (MushafDb) فلا يتكرر مصدران للعدّ.
 */
object MushafSurahs {

    val NAMES = arrayOf(
        "الفاتحة", "البقرة", "آل عمران", "النساء", "المائدة", "الأنعام", "الأعراف",
        "الأنفال", "التوبة", "يونس", "هود", "يوسف", "الرعد", "إبراهيم", "الحجر",
        "النحل", "الإسراء", "الكهف", "مريم", "طه", "الأنبياء", "الحج", "المؤمنون",
        "النور", "الفرقان", "الشعراء", "النمل", "القصص", "العنكبوت", "الروم",
        "لقمان", "السجدة", "الأحزاب", "سبأ", "فاطر", "يس", "الصافات", "ص",
        "الزمر", "غافر", "فصلت", "الشورى", "الزخرف", "الدخان", "الجاثية",
        "الأحقاف", "محمد", "الفتح", "الحجرات", "ق", "الذاريات", "الطور", "النجم",
        "القمر", "الرحمن", "الواقعة", "الحديد", "المجادلة", "الحشر", "الممتحنة",
        "الصف", "الجمعة", "المنافقون", "التغابن", "الطلاق", "التحريم", "الملك",
        "القلم", "الحاقة", "المعارج", "نوح", "الجن", "المزمل", "المدثر", "القيامة",
        "الإنسان", "المرسلات", "النبأ", "النازعات", "عبس", "التكوير", "الانفطار",
        "المطففين", "الانشقاق", "البروج", "الطارق", "الأعلى", "الغاشية", "الفجر",
        "البلد", "الشمس", "الليل", "الضحى", "الشرح", "التين", "العلق", "القدر",
        "البينة", "الزلزلة", "العاديات", "القارعة", "التكاثر", "العصر", "الهمزة",
        "الفيل", "قريش", "الماعون", "الكوثر", "الكافرون", "النصر", "المسد",
        "الإخلاص", "الفلق", "الناس",
    )

    /** اسم السورة بسريانها الآمن خارج النطاق — نص فارغ للرقم غير السليم */
    fun name(sura: Int): String = NAMES.getOrNull(sura - 1) ?: ""

    /** رقم بالأرقام العربية الهندية — توقيع التطبيق في كل عناوينه */
    fun arabicDigits(n: Int): String =
        n.toString().map { d -> if (d.isDigit()) '٠' + (d - '0') else d }.toCharArray().let { String(it) }

    /**
     * عنوان التحديد — آية واحدة «سورة البقرة · آية ١٠» ومُدى «سورة البقرة
     * · الآيات ١٠–١٤» — للتلاوة والمشاركة والنسخ والعلامة المرجعية.
     */
    fun caption(selection: MushafSelection): String {
        val first = selection.ayahs.first
        val last = selection.ayahs.last
        val ayahPart = if (first == last) {
            "آية ${arabicDigits(first)}"
        } else {
            "الآيات ${arabicDigits(first)}–${arabicDigits(last)}"
        }
        return "سورة ${name(selection.sura)} · $ayahPart"
    }
}
