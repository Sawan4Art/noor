    fun integrityProblems(): List<String> {
        val problems = ArrayList<String>()
        val countryNames = HashSet<String>()
        for (c in COUNTRIES) {
            if (c.name.isBlank()) problems.add("دولة بلا اسم")
            if (c.divisionLabel.isBlank()) problems.add("دولة بلا تسمية تقسيم: ${c.name}")
            if (!countryNames.add(c.name)) problems.add("دولة مكررة: ${c.name}")
            if (c.divisions.isEmpty()) problems.add("دولة بلا تقسيمات: ${c.name}")
            val divisionNames = HashSet<String>()
            for (d in c.divisions) {
                if (d.name.isBlank()) problems.add("تقسيم بلا اسم في ${c.name}")
                if (!divisionNames.add(d.name)) problems.add("تقسيم مكرر في ${c.name}: ${d.name}")
                if (d.cities.isEmpty()) problems.add("تقسيم بلا مدن: ${c.name}/${d.name}")
            }
        }
        return problems
    }
