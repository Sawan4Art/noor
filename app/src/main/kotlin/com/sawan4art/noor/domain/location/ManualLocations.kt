/**
 * قوائم التحديد اليدوي للموقع — بلاغ المالك 2026-11-11:
 * «عايز زر تحديد الموقع يدويا عن طريق اختيار الدوله ثم المحافظه ثم
 * المدينه ثم القريه ان وجدت و طبعا كل دوله حسب مسميتها مثلا امريكا
 * بدل المحافظه اسمها ولايه و هكذا».
 *
 * فالعقد هنا: هرمٌ من الأسماء فقط (دولة ← تقسيم إداري ← مدينة) —
 * **بلا إحداثيات**: الإحداثيات تأتي من الترميز الجغرافي للاسم المركّب
 * ([ForwardGeocoder]) فلا يُختلق رقمٌ ولا يُخطأ في موقعٍ لم يُقَس،
 * والقريةُ حقلٌ حرٌّ في الواجهة يُضاف إلى نصّ الترميز «إن وُجدت».
 *
 * كلُّ دولةٍ باسم تقسيمها هي: محافظة/ولاية/منطقة/إمارة/مقاطعة…
 * بتعيين [Country.divisionLabel] — عين ما طلب المالك. البيانات تُكتب
 * بنصٍّ مضغوطٍ يُحلَّل هنا: سطر الدولة «الاسم|تسمية التقسيم» ثم سطرٌ
 * لكل تقسيمٍ «التقسيم: مدينة، مدينة…» — وأسماؤها المؤكدةٌ حذرت في
 * كتابتها فلا تخمينَ في جغرافيا.
 */
object ManualLocations {

    /** تقسيم إداري — محافظة أو ولاية أو ما يقابلها، ومدنه المعروفة */
    data class Division(val name: String, val cities: List<String>)

    /** دولة باسمها وتسمية تقسيمها وأقسامها */
    data class Country(
        val name: String,
        /** تسمية التقسيم في هذه الدولة — محافظة/ولاية/منطقة/… */
        val divisionLabel: String,
        val divisions: List<Division>,
    )

    /** كل الدول — مصر أولاً ثم السعودية ثم باقي الدول */
    val COUNTRIES: List<Country> by lazy { RAW.map { parse(it) } }

    /** الدولة باسمها — والغريب يعود null فلا تُخترع دولة */
    fun country(name: String): Country? = COUNTRIES.firstOrNull { it.name == name }

    /** تقسيم دولةٍ باسمه */
    fun division(country: Country, name: String): Division? =
        country.divisions.firstOrNull { it.name == name }

    /**
     * نصّ الترميز الجغرافي من الاختيارات — «قرية، مدينة، تقسيم، دولة»
     * بترتيب الدقة من الأدق فالأعم، والحذف للفراغات يبقي النصّ نظيفاً.
     * دالةٌ نقيةٌ تُختبر آلياً.
     */
    fun geocodeQuery(
        country: String,
        division: String?,
        city: String?,
        village: String? = null,
    ): String = listOf(village, city, division, country)
        .filterNotNull()
        .filter { it.isNotBlank() }
        .joinToString("، ") { it.trim() }

    /**
     * سطر الموقع المعروض — قريةٌ فمدينةٌ فتقسيمٌ فدولة بعين عقد
     * سطر الموقع في التطبيق (أبو زعبل، الخانكة، القليوبية) — دالةٌ نقية.
     */
    fun locationLabel(
        country: String,
        division: String?,
        city: String?,
        village: String? = null,
    ): String = listOf(village, city, division, country)
        .filterNotNull()
        .filter { it.isNotBlank() }
        .joinToString("، ") { it.trim() }

    // ===== المحلل — سطر الدولة «الاسم|التسمية» وسطور التقسيمات =====

    private fun parse(def: String): Country {
        val lines = def.trimIndent().lines().filter { it.isNotBlank() }
        val head = lines.first().split("|")
        val divisions = lines.drop(1).map { line ->
            val parts = line.trim().split(":", limit = 2)
            Division(
                parts[0].trim(),
                parts.getOrNull(1)
                    ?.split("،", ",")
                    ?.map { it.trim() }
                    ?.filter { it.isNotEmpty() }
                    ?: emptyList(),
            )
        }
        return Country(head[0].trim(), head.getOrNull(1)?.trim() ?: "", divisions)
    }

